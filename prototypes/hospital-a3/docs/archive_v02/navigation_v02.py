"""A3 v0.2 integration navigation checks with standalone browser injection."""
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def check(label,cond):
 if not cond: raise AssertionError(label)
 checks.append(label)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.on('dialog',lambda d:d.accept())
 page.set_content((ROOT/'preview.html').read_text('utf-8'),wait_until='load')
 check('no redundant caution in main', '이 평가는 검증된 임상 위험도' not in page.locator('#a3-screen').inner_text())
 check('a3 main available',page.locator('#a3-screen').is_visible())
 check('plan sections folded by default',page.locator('[data-item][open]').count()==1)
 check('all six plan sections available',page.locator('[data-item]').count()==6)
 page.locator('[data-nav="patients"]').click()
 check('patient list opens',page.locator('#patient-dialog').is_visible())
 check('three patient records',page.locator('.patient-list-card').count()==3)
 page.locator('[data-patient-pick="SYN-003"][data-target-screen="assessment"]').click()
 check('patient pick opens A2 screen',page.locator('#aux-screen').is_visible() and page.get_by_role('heading',name='퇴원 후 관리 필요도 평가').is_visible())
 check('a2 renders six domain controls',page.locator('.a2-domain-btn').count()==6)
 check('a2 five editable fields',page.locator('[data-a2-field]').count()==5)
 page.locator('[data-a2-domain="medication"]').click()
 check('a2 domain selection opens medication',page.locator('#a2-field-reconciliation').is_visible())
 page.locator('#a2-field-reconciliation').select_option('complete')
 check('handoff enabled after field changed',page.locator('#handoff-a2').is_enabled())
 page.locator('#handoff-a2').click()
 check('A3 opens after handoff',page.locator('#a3-screen').is_visible())
 check('new assessment id after explicit handoff','AS-SYN-003-' in page.locator('#help-assessment-ref').inner_text())
 check('blocker notice remains after handoff', '발행 전 해결할 사항' in page.locator('#gate-banner').inner_text())
 page.locator('#gate-banner').click()
 check('blockers dialog opens',page.locator('#blockers-dialog').is_visible())
 check('all blockers represented',page.locator('.blocker-jump').count()>=1)
 page.locator('.blocker-jump').first.click()
 check('blocker jumps to relevant tab',page.locator('[data-tab="issues"]').get_attribute('aria-selected')=='true')
 check('jumped issue gets highlight',page.locator('.jump-highlight').count()==1)
 page.locator('#gate-banner').click()
 page.locator('[data-blocker-id="item-medication-source"]').click()
 check('plan blocker opens correct folded section',page.locator('[data-item="medication"]').get_attribute('open') is not None and page.locator('[data-item="medication"]').is_visible())
 page.locator('#preview-toggle').click()
 check('preview collapses to full-width edit',page.locator('#shell').evaluate("e=>e.classList.contains('preview-collapsed')") and page.locator('#preview-pane').is_hidden())
 page.locator('#preview-toggle').click()
 check('preview expands again',page.locator('#preview-pane').is_visible())
 page.locator('[data-nav="patient-preview"]').click()
 check('standalone patient preview opens',page.locator('.full-patient-preview').is_visible())
 page.locator('#back-to-plan').click()
 check('return to A3 works',page.locator('#a3-screen').is_visible())
 page.locator('#top-help').click()
 check('mockup explanation moved to help', '이 평가는 검증된 임상 위험도' in page.locator('#help-dialog').inner_text())
 page.locator('[data-close-dialog="help-dialog"]').click()
 check('help dialog closes',not page.locator('#help-dialog').is_visible())
 for width in (320,390,800,801,1024,1440):
  page.set_viewport_size({'width':width,'height':900});page.wait_for_timeout(40)
  check(f'A3 responsive no overflow {width}', page.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')<=1)
  page.locator('[data-nav="assessment"]').click()
  check(f'A2 responsive no overflow {width}', page.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')<=1)
  page.locator('[data-nav="plan"]').click()
 page.set_viewport_size({'width':1440,'height':900})
 page.locator('#reset').click()
 page.locator('[data-nav="patients"]').click()
 page.locator('[data-patient-pick="SYN-001"][data-target-screen="plan"]').click()
 check('reset restores a single expanded plan section',page.locator('[data-item][open]').count()==1)
 page.locator('#toast').evaluate('el=>el.hidden=true')
 page.screenshot(path=str(ROOT/'examples'/'a3-v02-desktop.png'),full_page=True)
 page.locator('#gate-banner').click()
 page.screenshot(path=str(ROOT/'examples'/'a3-v02-blockers.png'),full_page=False)
 page.locator('[data-close-dialog="blockers-dialog"]').click()
 page.locator('[data-nav="assessment"]').click()
 page.screenshot(path=str(ROOT/'examples'/'a3-v02-assessment.png'),full_page=False)
 check('no JS errors',not errors)
 print(f'NAVIGATION V0.2 PASS {len(checks)} checks')
 for x in checks:print(' -',x)
 browser.close()
