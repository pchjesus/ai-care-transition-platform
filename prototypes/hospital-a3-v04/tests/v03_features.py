from browser_support import load_app, ARTIFACTS
"""Additional A3 v0.3 interactive checks. Injected standalone page, not origin-security testing."""
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def chk(msg,v):
 if not v: raise AssertionError(msg)
 checks.append(msg)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':900})
 page.on('dialog',lambda d:d.accept())
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 load_app(page,ROOT)
 chk('v0.3 initially six domains',page.locator('#domain-grid .domain').count()==6)
 chk('preview initially collapsed',page.locator('#preview-pane').is_hidden())
 top=page.locator('.patient-strip').bounding_box();gate=page.locator('.gate-banner').bounding_box()
 chk('patient + gate on same row at 1440', abs(top['y']-gate['y'])<4)
 chk('upper strip is compact',top['height']<140 and gate['height']<140)
 page.locator('[data-item="today"] summary').click() # close first to keep focused test
 page.locator('[data-item="today"] summary').click()
 page.locator('[data-item="today"] [data-action="select-source"]').click()
 chk('source picker opens',page.locator('#source-dialog').is_visible())
 chk('source human titles',page.locator('#source-dialog').get_by_text('퇴원교육 이해 확인지').count()>=1)
 chk('confirmed relevant source selectable',page.locator('[data-connect-source="SRC-SYN001-NUR-01"]').is_enabled())
 chk('unconfirmed source disabled',page.locator('[data-connect-source="SRC-SYN001-MED-01"]').is_disabled())
 page.locator('[data-connect-source="SRC-SYN001-NUR-01"]').click()
 chk('source connected but not automatically reviewed',page.locator('[data-item="today"] [data-edit="verified"]').is_checked()==False)
 chk('source title shown not raw ID',page.locator('[data-item="today"] .source-choose strong').inner_text()=='퇴원교육 이해 확인지')
 page.locator('[data-item="today"] [data-edit="verified"]').check()
 chk('nurse may review nursing item',page.locator('[data-item="today"] [data-edit="verified"]').is_checked())
 page.locator('[data-nav="learn"]').click()
 chk('learning tab opens',page.get_by_role('heading',name='설명과 실습').is_visible())
 chk('learning has 5 units',page.locator('.learning-nav button').count()==5)
 page.locator('[data-learn-unit="terms"]').click()
 chk('FAQ search field visible',page.locator('#learn-search').is_visible())
 page.locator('#learn-search').fill('스냅샷')
 chk('FAQ search finds relevant topic',page.locator('.learn-faq details').count()>=1)
 page.locator('[data-learn-unit="source"]').click()
 page.locator('[data-learn-source-patient="SYN-003"]').click()
 chk('learning source list opens',page.locator('#source-dialog').is_visible())
 chk('record A and B are visible',page.get_by_text('퇴원약 목록 A',exact=True).count()==1 and page.get_by_text('퇴원약 목록 B',exact=True).count()==1)
 page.locator('[data-close-dialog="source-dialog"]').click()
 page.locator('[data-learn-unit="practice"]').click()
 chk('four cases in learning',page.locator('[data-study-start]').count()==4)
 page.locator('[data-study-start="SYN-003"]').click()
 chk('practice starts with third synthetic patient',page.locator('#patient-name').inner_text().startswith('최도현'))
 chk('SYN003 plan cannot be approved',page.locator('#gate-banner').inner_text().find('해결할 사항')>=0)
 page.locator('[data-nav="learn"]').click()
 chk('practice banner visible in study mode',page.locator('.study-banner').is_visible())
 page.locator('[data-learn-unit="source"]').click()
 page.locator('[data-learn-source-patient="SYN-003"]').click() # use current case; source only
 chk('locked response visible',page.locator('[data-unlock-source="SRC-SYN003-MED-C"]').is_visible())
 page.locator('[data-unlock-source="SRC-SYN003-MED-C"]').click()
 chk('fictional verification reply unlocks', '회신을 받았습니다' in page.locator('#toast').inner_text())
 page.locator('[data-nav="assessment"]').click()
 page.locator('[data-a2-domain="medication"]').click()
 page.locator('[data-a2-field="reconciliation"]').select_option('complete')
 chk('A2 input dirty after correction',page.locator('#handoff-a2').is_enabled())
 page.locator('#handoff-a2').click()
 chk('A2 corrected value handed to A3',page.locator('#workflow-state').inner_text().find('초안')>=0)
 page.locator('[data-nav="learn"]').click()
 page.locator('[data-study-leave]').click()
 chk('return to original patient after practice',page.locator('#patient-name').inner_text().startswith('이정희'))
 chk('normal source selection remained intact after practice',page.locator('[data-item="today"] .source-choose strong').inner_text()=='퇴원교육 이해 확인지')
 page.locator('[data-nav="learn"]').click()
 page.locator('[data-learn-unit="practice"]').click()
 page.locator('[data-study-start="SYN-004"]').click()
 chk('SYN004 opens with published v1',page.locator('#workflow-state').inner_text()=='발행 완료')
 chk('SYN004 existing publication retained',page.locator('#preview-toggle').is_visible())
 page.locator('#revise').click()
 chk('SYN004 revision creates v2', 'v2.0' in page.locator('#version-chip').inner_text())
 chk('SYN004 old v1 remains published',page.locator('#show-current').is_enabled())
 page.locator('[data-nav="learn"]').click()
 page.locator('[data-study-leave]').click()
 for width in (320,390,800,801,1024,1440):
  page.set_viewport_size({'width':width,'height':880})
  page.locator('[data-nav="plan"]').click()
  chk(f'responsive plan no overflow {width}',page.evaluate('document.documentElement.scrollWidth-document.documentElement.clientWidth')<=1)
  page.locator('[data-nav="learn"]').click()
  chk(f'responsive learning no overflow {width}',page.evaluate('document.documentElement.scrollWidth-document.documentElement.clientWidth')<=1)
 page.set_viewport_size({'width':1440,'height':900})
 page.locator('[data-nav="plan"]').click()
 page.screenshot(path=str(ARTIFACTS/'a3-v03-desktop.png'),full_page=False)
 page.locator('[data-nav="learn"]').click()
 page.locator('[data-learn-unit="practice"]').click()
 page.screenshot(path=str(ARTIFACTS/'a3-v03-learning.png'),full_page=False)
 chk('no page errors',not errors)
 print('V0.3 FEATURES PASS',len(checks))
 browser.close()
